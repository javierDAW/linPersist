// TestNormalizeHostname pins the ADR-0006 contract: lowercase + trim +
// truncate at first '.'.
func TestNormalizeHostname(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
	}{
		{"already canonical", "web-01", "web-01"},
		{"uppercase", "WEB-01", "web-01"},
		{"mixed case", "Web-01", "web-01"},
		{"fqdn", "web-01.prod.example.com", "web-01"},
		{"uppercase fqdn", "WEB-01.PROD.EXAMPLE.COM", "web-01"},
		{"leading whitespace", "  web-01", "web-01"},
		{"trailing whitespace", "web-01\n", "web-01"},
		{"trailing CR", "web-01\r", "web-01"},
		{"empty", "", ""},
		{"only domain dot", ".example.com", ""},
		{"numeric", "host-42", "host-42"},
		{"underscore preserved", "build_box", "build_box"},
		{"single dot truncates everything after", "a.b.c.d", "a"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := normalizeHostname(tc.in)
			if got != tc.want {
				t.Errorf("normalizeHostname(%q) = %q; want %q", tc.in, got, tc.want)
			}
		})
	}
}

// TestNormalizeHostname_Idempotent: normalize(normalize(x)) == normalize(x).
func TestNormalizeHostname_Idempotent(t *testing.T) {
	inputs := []string{
		"WEB-01",
		"web-01.prod.example.com",
		"  Host.With.Whitespace  ",
		"",
		"already-good",
	}
	for _, in := range inputs {
		once := normalizeHostname(in)
		twice := normalizeHostname(once)
		if once != twice {
			t.Errorf("normalizeHostname not idempotent for %q: once=%q twice=%q", in, once, twice)
		}
	}
}

// TestHashHostname_CollapsesCosmeticVariants is the load-bearing test
// for the ADR-0006 LFA property: every cosmetic variant of the same
// logical hostname MUST produce the same digest.
func TestHashHostname_CollapsesCosmeticVariants(t *testing.T) {
	variants := []string{
		"web-01",
		"WEB-01",
		"Web-01",
		"web-01.prod.example.com",
		"WEB-01.PROD.EXAMPLE.COM",
		"  web-01  ",
		"web-01\n",
	}
	want := hashHostname("web-01")
	for _, v := range variants {
		got := hashHostname(v)
		if got != want {
			t.Errorf("hashHostname(%q) = %q; want %q (same as canonical 'web-01')", v, got, want)
		}
	}
}

// TestHashHostname_DistinctHostsDiffer guards against a normalization
// bug that flattens everything to the empty string: distinct
// canonical hostnames MUST produce distinct digests.
func TestHashHostname_DistinctHostsDiffer(t *testing.T) {
	a := hashHostname("web-01")
	b := hashHostname("web-02")
	c := hashHostname("db-01")
	if a == b || a == c || b == c {
		t.Fatalf("expected distinct digests, got a=%q b=%q c=%q", a, b, c)
	}
}

// TestHashHostname_Prefix confirms the "sha256:" prefix mandated by
// schema-v1.md.
func TestHashHostname_Prefix(t *testing.T) {
	got := hashHostname("web-01")
	if !strings.HasPrefix(got, "sha256:") {
		t.Errorf("hashHostname(%q) = %q; want prefix \"sha256:\"", "web-01", got)
	}
	// Body should be 64 hex chars.
	body := strings.TrimPrefix(got, "sha256:")
	if len(body) != 64 {
		t.Errorf("hash body length = %d; want 64", len(body))
	}
	if _, err := hex.DecodeString(body); err != nil {
		t.Errorf("hash body is not valid hex: %v", err)
	}
}

// TestHashHostname_MatchesManualSha256 cross-checks the digest against
// an independent computation, in case the implementation is refactored
// to use a different hashing path.
func TestHashHostname_MatchesManualSha256(t *testing.T) {
	const canonical = "web-01"
	sum := sha256.Sum256([]byte(canonical))
	want := "sha256:" + hex.EncodeToString(sum[:])

	got := hashHostname("WEB-01.prod.example.com")
	if got != want {
		t.Errorf("hashHostname normalized digest = %q; want %q", got, want)
	}
}

// TestReadOSRelease covers the parsing shapes most distros actually
// ship. The function is forgiving: unknown keys ignored, quoted
// values unquoted, comments and blank lines tolerated.
func TestReadOSRelease(t *testing.T) {
	cases := []struct {
		name       string
		content    string
		wantID     string
		wantVerID  string
	}{
		{
			name: "ubuntu 22.04 style",
			content: `PRETTY_NAME="Ubuntu 22.04.3 LTS"
NAME="Ubuntu"
VERSION_ID="22.04"
VERSION="22.04.3 LTS (Jammy Jellyfish)"
ID=ubuntu
ID_LIKE=debian
`,
			wantID:    "ubuntu",
			wantVerID: "22.04",
		},
		{
			name: "rhel 8 style",
			content: `NAME="Red Hat Enterprise Linux"
VERSION="8.9 (Ootpa)"
ID="rhel"
ID_LIKE="fedora"
VERSION_ID="8.9"
`,
			wantID:    "rhel",
			wantVerID: "8.9",
		},
		{
			name: "alpine 3.19 style (unquoted)",
			content: `NAME="Alpine Linux"
ID=alpine
VERSION_ID=3.19.1
PRETTY_NAME="Alpine Linux v3.19"
`,
			wantID:    "alpine",
			wantVerID: "3.19.1",
		},
		{
			name: "with comments and blank lines",
			content: `# /etc/os-release
# generated by os-release.sh

ID=debian
VERSION_ID="11"
`,
			wantID:    "debian",
			wantVerID: "11",
		},
		{
			name:      "missing ID falls through to empty",
			content:   `PRETTY_NAME="Some Distro"`,
			wantID:    "",
			wantVerID: "",
		},
		{
			name:      "single-quoted values",
			content:   "ID='arch'\nVERSION_ID='rolling'\n",
			wantID:    "arch",
			wantVerID: "rolling",
		},
	}

	dir := t.TempDir()
	for i, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(dir, "os-release-"+itoa(i))
			if err := os.WriteFile(path, []byte(tc.content), 0o644); err != nil {
				t.Fatalf("write fixture: %v", err)
			}
			gotID, gotVer := readOSRelease(path)
			if gotID != tc.wantID || gotVer != tc.wantVerID {
				t.Errorf("readOSRelease() = (%q, %q); want (%q, %q)",
					gotID, gotVer, tc.wantID, tc.wantVerID)
			}
		})
	}
}

func TestReadOSRelease_MissingFile(t *testing.T) {
	id, ver := readOSRelease(filepath.Join(t.TempDir(), "does-not-exist"))
	if id != "" || ver != "" {
		t.Errorf("readOSRelease on missing file = (%q, %q); want both empty", id, ver)
	}
}

func TestReadFirstLine(t *testing.T) {
	dir := t.TempDir()
	cases := []struct {
		name      string
		content   string
		want      string
		wantErr   bool
	}{
		{"single line no trailing newline", "5.15.0-91-generic", "5.15.0-91-generic", false},
		{"single line with trailing newline", "5.15.0-91-generic\n", "5.15.0-91-generic", false},
		{"multi-line returns first", "first-line\nsecond-line\nthird\n", "first-line", false},
		{"empty file returns error", "", "", true},
	}
	for i, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(dir, "first-line-"+itoa(i))
			if err := os.WriteFile(path, []byte(tc.content), 0o644); err != nil {
				t.Fatalf("write fixture: %v", err)
			}
			got, err := readFirstLine(path)
			if tc.wantErr {
				if err == nil {
					t.Errorf("readFirstLine(%q) returned nil error; want non-nil", path)
				}
				return
			}
			if err != nil {
				t.Errorf("readFirstLine(%q) error = %v; want nil", path, err)
				return
			}
			if got != tc.want {
				t.Errorf("readFirstLine(%q) = %q; want %q", path, got, tc.want)
			}
		})
	}
}

func TestReadFirstLine_MissingFile(t *testing.T) {
	_, err := readFirstLine(filepath.Join(t.TempDir(), "absent"))
	if err == nil {
		t.Error("readFirstLine on missing file returned nil error; want non-nil")
	}
}

// TestFormatMode covers the four-digit octal contract used by every
// Record's `mode` field.
func TestFormatMode(t *testing.T) {
	cases := []struct {
		in   uint32
		want string
	}{
		{0o644, "0644"},
		{0o755, "0755"},
		{0o600, "0600"},
		{0o000, "0000"},
		{0o4755, "4755"}, // setuid
		{0o2755, "2755"}, // setgid
		{0o1777, "1777"}, // sticky (/tmp)
		// High bits beyond the permission/sticky range MUST be masked
		// off: only the low 12 bits matter for the mode string.
		{0o100644, "0644"}, // S_IFREG | 0644 -> still "0644"
	}
	for _, tc := range cases {
		got := FormatMode(tc.in)
		if got != tc.want {
			t.Errorf("FormatMode(%#o) = %q; want %q", tc.in, got, tc.want)
		}
	}
}

// itoa is a no-import-needed integer-to-string for short test labels.
// Avoids pulling in strconv just for fixture filenames.
func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	return string(b[i:])
}
